const MET_DATE = new Date("2026-04-26T01:15:00");
function tick() {
  const d = Math.max(0, Date.now() - MET_DATE), L = STR[lang].units;
  const v = [d / 864e5 | 0, (d / 36e5 | 0) % 24, (d / 6e4 | 0) % 60, (d / 1e3 | 0) % 60];
  const pc = [(v[0] % 30) / 30, v[1] / 24, v[2] / 60, v[3] / 60];
  if($("counter")) {
    $("counter").innerHTML = v.map((n, i) => `<div class="unit" style="--p:${pc[i] * 100}"><b>${n}</b><span>${L[i]}</span></div>`).join("");
  }
}
setInterval(tick, 1000);

