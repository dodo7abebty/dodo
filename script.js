let lang = "ar";
const $ = id => document.getElementById(id);

function render() {
  const t = STR[lang], root = document.documentElement;
  root.lang = lang; root.dir = lang === "ar" ? "rtl" : "ltr";
  document.title = lang === "ar" ? "لدودتي ♥" : "For Dodoty ♥";
  $("langBtn").textContent = lang === "ar" ? "EN" : "ع";
  
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.dataset.i18n;
    if (t[key]) el.textContent = t[key];
  });

  const letterBody = $("letterBody");
  if (letterBody && letterBody.classList.contains("open")) {
    letterBody.innerHTML = `<h3>${t.letterTitle}</h3>` +
      t.letter.map((p, i) => `<p style="--i:${i}">${p}</p>`).join("") +
      `<p class="sign" style="--i:${t.letter.length}">${t.sign}</p>`;
  }

  const cardsContainer = $("cards");
  if (cardsContainer) {
    cardsContainer.innerHTML = t.cards.map(c => `
      <button class="card" aria-label="${c[1]}">
        <div class="inner">
          <div class="face"><span class="icon">${c[0]}</span><strong>${c[1]}</strong></div>
          <div class="face back"><p>${c[2]}</p></div>
        </div>
      </button>`).join("");
    document.querySelectorAll(".card").forEach(b => b.onclick = () => b.classList.toggle("on"));
  }

  const notesContainer = $("notes");
  if (notesContainer && t.notes) {
    notesContainer.innerHTML = t.notes.map(n =>
      `<button class="note"><span class="note-head">${n[0]}<i>+</i></span>` +
      `<span class="note-body"><span><span class="note-text">${n[1]}</span></span></span></button>`).join("");
    document.querySelectorAll(".note").forEach(b => b.onclick = () => b.classList.toggle("open"));
  }

  tick();
}

$("langBtn").onclick = () => {
  lang = lang === "ar" ? "en" : "ar";
  render();
};

