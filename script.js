const cv = $("bg");
const cx = cv ? cv.getContext("2d") : null;
const still = matchMedia("(prefers-reduced-motion: reduce)").matches;
let W, H, hearts = [], stars = [], pColor = "240,163,182";

function resize() {
  if (!cv) return;
  W = cv.width = innerWidth; H = cv.height = innerHeight;
  const n = Math.round(W / 45);
  hearts = Array.from({ length: n }, () => newHeart(true));
  stars  = Array.from({ length: 90 }, () => ({ x: Math.random() * W, y: Math.random() * H, r: Math.random() * 1.4 + .3, t: Math.random() * 6 }));
}
const newHeart = init => ({ x: Math.random() * W, y: init ? Math.random() * H : H + 30, s: 8 + Math.random() * 20,
                            v: .25 + Math.random() * .6, d: Math.random() * 6, a: .12 + Math.random() * .35 });

function heart(x, y, s) {
  if (!cx) return;
  cx.beginPath(); cx.moveTo(x, y + s * .3);
  cx.bezierCurveTo(x, y, x - s / 2, y, x - s / 2, y + s * .3);
  cx.bezierCurveTo(x - s / 2, y + s * .65, x, y + s * .8, x, y + s);
  cx.bezierCurveTo(x, y + s * .8, x + s / 2, y + s * .65, x + s / 2, y + s * .3);
  cx.bezierCurveTo(x + s / 2, y, x, y, x, y + s * .3); cx.fill();
}
function frame(ts = 0) {
  if (!cx) return;
  cx.clearRect(0, 0, W, H);
  if (night) stars.forEach(s => {
    cx.fillStyle = `rgba(255,240,235,${.3 + .5 * Math.abs(Math.sin(ts / 1200 + s.t))})`;
    cx.beginPath(); cx.arc(s.x, s.y, s.r, 0, 7); cx.fill();
  });
  hearts.forEach((h, i) => {
    const dx = h.x - mx, dy = h.y - my, dd = Math.hypot(dx, dy) || 1;
    if (dd < 140) { h.x += dx / dd * 2.2; h.y += dy / dd * 2.2; }
    cx.fillStyle = `rgba(${pColor},${h.a})`;
    heart(h.x + Math.sin(ts / 1500 + h.d) * 18, h.y, h.s);
    h.y -= h.v;
    if (h.y < -40) hearts[i] = newHeart(false);
  });
  if (!still) requestAnimationFrame(frame);
}

